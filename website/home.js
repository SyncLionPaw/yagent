const SHOTS = [1, 2, 3, 4]
const LANG_TAGS = { zh: 'zh-CN', ja: 'ja', en: 'en' }
const langRoot = document.getElementById('lang')
const langBtn = langRoot.querySelector('.lang-btn')
const langMenu = langRoot.querySelector('.menu-panel')
const productImage = document.getElementById('productImage')
const tabs = [...document.querySelectorAll('[data-shot]')]
let currentLang = 'zh'
let currentShot = 0

function detectLang() {
    const saved = localStorage.getItem('yagent-lang')
    if (saved && I18N[saved]) return saved
    const nav = (navigator.language || 'en').toLowerCase()
    if (nav.startsWith('zh')) return 'zh'
    if (nav.startsWith('ja')) return 'ja'
    return 'en'
}

function renderShot(index) {
    currentShot = index
    const dict = I18N[currentLang]
    const n = SHOTS[index]
    tabs.forEach((tab, i) => {
        const selected = i === index
        tab.setAttribute('aria-selected', String(selected))
        tab.tabIndex = selected ? 0 : -1
    })
    document.getElementById('productPanel').setAttribute('aria-labelledby', `shotTab${index}`)
    document.getElementById('productTitle').textContent = dict[`shot${n}Title`]
    document.getElementById('productDescription').textContent = dict[`shot${n}Description`]
    productImage.classList.add('switching')
    productImage.src = `assets/showcase/${n}.webp`
    productImage.alt = dict[`shot${n}Alt`]
    const reveal = () => productImage.classList.remove('switching')
    if (productImage.complete) requestAnimationFrame(reveal)
    else productImage.addEventListener('load', reveal, { once: true })
}

function setLang(lang) {
    currentLang = lang
    const dict = I18N[lang]
    document.documentElement.lang = LANG_TAGS[lang]
    document.title = dict.pageTitle
    document.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = dict[el.dataset.i18n] || ''
    })
    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
        el.setAttribute('alt', dict[el.dataset.i18nAlt] || '')
    })
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        el.setAttribute('aria-label', dict[el.dataset.i18nAriaLabel] || '')
    })
    langMenu.querySelectorAll('[data-lang]').forEach(item => {
        const on = item.dataset.lang === lang
        item.setAttribute('aria-selected', String(on))
        if (on) langRoot.querySelector('.lang-label').textContent = item.textContent.trim()
    })
    renderShot(currentShot)
    localStorage.setItem('yagent-lang', lang)
}

function closeLangMenu() {
    langRoot.classList.remove('open')
    langBtn.setAttribute('aria-expanded', 'false')
}

langBtn.addEventListener('click', () => {
    if (langRoot.classList.contains('open')) {
        closeLangMenu()
        return
    }
    window.YagentTheme.closeTheme()
    langRoot.classList.add('open')
    langBtn.setAttribute('aria-expanded', 'true')
    const current = langMenu.querySelector('[aria-selected="true"]')
    ;(current || langMenu.firstElementChild).focus()
})

langMenu.addEventListener('click', event => {
    const item = event.target.closest('[data-lang]')
    if (!item) return
    setLang(item.dataset.lang)
    closeLangMenu()
    langBtn.focus()
})

document.addEventListener('click', event => {
    if (!langRoot.contains(event.target)) closeLangMenu()
})

document.addEventListener('keydown', event => {
    if (event.key === 'Escape') {
        closeLangMenu()
        return
    }
    if (!langRoot.classList.contains('open') || !['ArrowDown', 'ArrowUp'].includes(event.key)) return
    event.preventDefault()
    const items = [...langMenu.querySelectorAll('[data-lang]')]
    const at = items.indexOf(document.activeElement)
    const step = event.key === 'ArrowDown' ? 1 : -1
    items[(at + step + items.length) % items.length].focus()
})

tabs.forEach((tab, index) => {
    tab.addEventListener('click', () => renderShot(index))
    tab.addEventListener('keydown', event => {
        let next = index
        if (event.key === 'ArrowRight' || event.key === 'ArrowDown') next = (index + 1) % tabs.length
        else if (event.key === 'ArrowLeft' || event.key === 'ArrowUp') next = (index - 1 + tabs.length) % tabs.length
        else if (event.key === 'Home') next = 0
        else if (event.key === 'End') next = tabs.length - 1
        else return
        event.preventDefault()
        renderShot(next)
        tabs[next].focus()
    })
})

async function copyText(text) {
    if (navigator.clipboard && window.isSecureContext) {
        try {
            await navigator.clipboard.writeText(text)
            return
        } catch {
            // 某些浏览器拒绝异步剪贴板权限，继续尝试兼容复制方式。
        }
    }
    const textarea = document.createElement('textarea')
    textarea.value = text
    textarea.style.position = 'fixed'
    textarea.style.opacity = '0'
    document.body.appendChild(textarea)
    textarea.select()
    const ok = document.execCommand('copy')
    textarea.remove()
    if (!ok) throw new Error('copy failed')
}

const copyButton = document.getElementById('copyAgentInstruction')
copyButton.addEventListener('click', async () => {
    const text = document.getElementById('agentInstruction').textContent.trim()
    const dict = I18N[currentLang]
    try {
        await copyText(text)
        copyButton.classList.add('copied')
        document.getElementById('copyLabel').textContent = dict.copied
        document.getElementById('copyStatus').textContent = dict.copySuccess
        window.setTimeout(() => {
            copyButton.classList.remove('copied')
            document.getElementById('copyLabel').textContent = I18N[currentLang].copy
            document.getElementById('copyStatus').textContent = ''
        }, 2400)
    } catch {
        document.getElementById('copyStatus').textContent = dict.copyError
    }
})

